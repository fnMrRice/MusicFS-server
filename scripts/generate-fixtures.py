"""Generate deterministic, redistributable MusicFS audio test fixtures."""

import argparse
import hashlib
import json
import math
from pathlib import Path
import struct
import subprocess
import wave

RATE = 48000
AMPLITUDE = 0.125
DURATION_MS = 6000


def write_wave(path, prefix_ms=0, alternate=False):
    frame_count = (DURATION_MS + prefix_ms) * RATE // 1000
    content = bytearray(frame_count * 4)
    for frame in range(frame_count):
        time = frame / RATE - prefix_ms / 1000
        if time < 0:
            continue
        segment = min(2, int(time // 2))
        frequency = (330 if alternate else 220) * (segment + 1)
        local_time = time % 2
        # Smooth 10 ms edges avoid discontinuity clicks between markers.
        fade = min(1.0, local_time / 0.01, (2 - local_time) / 0.01)
        value = int(round(32767 * AMPLITUDE * fade * math.sin(2 * math.pi * frequency * time)))
        left = value if segment != 1 else 0
        right = value if segment != 0 else 0
        struct.pack_into("<hh", content, frame * 4, left, right)
    with wave.open(str(path), "wb") as output:
        output.setnchannels(2)
        output.setsampwidth(2)
        output.setframerate(RATE)
        output.writeframes(content)


def convert(ffmpeg, source, output, codec_args):
    args = [str(ffmpeg), "-hide_banner", "-loglevel", "error", "-y", "-i", str(source),
            "-map_metadata", "-1", "-bitexact", *codec_args, str(output)]
    subprocess.run(args, check=True, capture_output=True)


def probe(ffprobe, path):
    result = subprocess.run(
        [str(ffprobe), "-v", "error", "-select_streams", "a:0", "-show_entries",
         "stream=codec_name,sample_rate,channels,duration,bit_rate:format=duration,bit_rate",
         "-of", "json", str(path)], check=True, capture_output=True, text=True)
    return json.loads(result.stdout)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ffmpeg", type=Path, required=True)
    parser.add_argument("--ffprobe", type=Path)
    args = parser.parse_args()
    ffprobe = args.ffprobe or args.ffmpeg.with_name("ffprobe" + args.ffmpeg.suffix)
    root = Path(__file__).resolve().parents[1] / "tests" / "testdata" / "audio"
    root.mkdir(parents=True, exist_ok=True)
    write_wave(root / "markers.wav")
    write_wave(root / "silence-prefix.wav", prefix_ms=2000)
    write_wave(root / "中文 空格曲目.wav", alternate=True)
    (root / "corrupt.wav").write_bytes(b"RIFF\xff\xff\xff\xffWAVEinvalid-test-fixture")
    (root / "empty.wav").write_bytes(b"")
    convert(args.ffmpeg, root / "markers.wav", root / "processing.aiff", ["-c:a", "pcm_s24be"])
    convert(args.ffmpeg, root / "markers.wav", root / "lossless.flac", ["-c:a", "flac"])
    convert(args.ffmpeg, root / "silence-prefix.wav", root / "vbr-untagged.mp3",
            ["-c:a", "libmp3lame", "-q:a", "4", "-write_xing", "1", "-id3v2_version", "0", "-write_id3v1", "0"])
    version = subprocess.run([str(args.ffmpeg), "-version"], check=True,
                             capture_output=True, text=True).stdout.splitlines()[0]
    manifest = {
        "license": "CC0-1.0", "source": "Synthetic sine waves generated by scripts/generate-fixtures.py",
        "generator": {"sampleRateHz": RATE, "channels": 2, "sampleBits": 16,
                      "peakAmplitude": AMPLITUDE, "peakDbFS": 20 * math.log10(AMPLITUDE),
                      "segmentMs": 2000, "fadeMs": 10, "ffmpeg": version},
        "markers": [{"startMs": 0, "endMs": 2000, "frequencyHz": 220, "channel": "left"},
                    {"startMs": 2000, "endMs": 4000, "frequencyHz": 440, "channel": "right"},
                    {"startMs": 4000, "endMs": 6000, "frequencyHz": 660, "channel": "both"}],
        "files": [],
    }
    for path in sorted(root.iterdir()):
        if path.suffix not in {".wav", ".aiff", ".flac", ".mp3"}:
            continue
        data = path.read_bytes()
        malformed = path.name in {"corrupt.wav", "empty.wav"}
        entry = {"name": path.name, "sizeBytes": len(data), "sha512": hashlib.sha512(data).hexdigest(),
                 "expectedValid": not malformed, "musicTags": "none",
                 "purpose": "invalid input" if malformed else "playback and seek marker"}
        if not malformed:
            entry["probe"] = probe(ffprobe, path)
        if path.name == "silence-prefix.wav" or path.suffix == ".mp3":
            entry["prefixSilenceMs"] = 2000
        if path.name == "中文 空格曲目.wav":
            entry["frequencyMultiplier"] = 1.5
        if path.suffix == ".mp3":
            packets = subprocess.run([str(ffprobe), "-v", "error", "-select_streams", "a:0",
                                      "-show_entries", "packet=size", "-of", "json", str(path)],
                                     check=True, capture_output=True, text=True)
            sizes = sorted({int(p["size"]) for p in json.loads(packets.stdout)["packets"]})
            entry["packetSizesBytes"] = sizes
            if len(sizes) < 2:
                raise RuntimeError("VBR fixture does not contain varying frame sizes")
        manifest["files"].append(entry)
    (root / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Generated {len(manifest['files'])} audio fixtures")


if __name__ == "__main__":
    main()
