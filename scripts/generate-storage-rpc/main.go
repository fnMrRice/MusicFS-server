// Command generate-storage-rpc generates the typed persistence client from the
// authoritative domain repository interfaces. Run from the server directory.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"github.com/fnMrRice/MusicFS-server/src/storage"
)

func main() {
	methods := map[string]reflect.Method{}
	for _, typ := range []reflect.Type{reflect.TypeFor[storage.Backend](), reflect.TypeFor[storage.Maintenance]()} {
		for i := 0; i < typ.NumMethod(); i++ {
			m := typ.Method(i)
			if m.Name != "Close" {
				methods[m.Name] = m
			}
		}
	}
	names := make([]string, 0, len(methods))
	for name := range methods {
		names = append(names, name)
	}
	sort.Strings(names)
	dir := filepath.Join("src", "storage", "rpcbackend")
	if err := os.MkdirAll(dir, 0700); err != nil {
		panic(err)
	}
	for part := 0; part*24 < len(names); part++ {
		var body bytes.Buffer
		imports := map[string]bool{}
		for _, name := range names[part*24 : min((part+1)*24, len(names))] {
			t := methods[name].Type
			if t.NumIn() < 1 || t.In(0).String() != "context.Context" || t.NumOut() < 1 {
				panic("unsupported persistence signature: " + name)
			}
			hasError := t.Out(t.NumOut()-1).String() == "error"
			valueCount := t.NumOut()
			if hasError {
				valueCount--
			}
			args, values, results, targets, returned := []string{}, []string{}, []string{}, []string{}, []string{}
			for i := 0; i < t.NumIn(); i++ {
				collectImports(t.In(i), imports)
				args = append(args, fmt.Sprintf("a%d %s", i, t.In(i)))
				if i > 0 {
					values = append(values, fmt.Sprintf("a%d", i))
				}
			}
			for i := 0; i < valueCount; i++ {
				collectImports(t.Out(i), imports)
				results = append(results, fmt.Sprintf("r%d %s", i, t.Out(i)))
				targets = append(targets, fmt.Sprintf("&r%d", i))
				returned = append(returned, fmt.Sprintf("r%d", i))
			}
			assignment := "_"
			if hasError {
				results = append(results, "err error")
				returned = append(returned, "err")
				assignment = "err"
			}
			if !hasError {
				if name != "ProviderScanState" || valueCount != 1 || t.Out(0).Kind() != reflect.String {
					panic("persistence signature needs an explicit failure result: " + name)
				}
				fmt.Fprintf(&body, "func (c *Client) %s(%s) (%s) {\nif err := c.Invoke(a0, %q, []any{%s}, []any{%s}); err != nil { return \"failed\" }\nreturn %s\n}\n\n", name, strings.Join(args, ", "), strings.Join(results, ", "), name, strings.Join(values, ", "), strings.Join(targets, ", "), strings.Join(returned, ", "))
				continue
			}
			fmt.Fprintf(&body, "func (c *Client) %s(%s) (%s) {\n%s = c.Invoke(a0, %q, []any{%s}, []any{%s})\nreturn %s\n}\n\n", name, strings.Join(args, ", "), strings.Join(results, ", "), assignment, name, strings.Join(values, ", "), strings.Join(targets, ", "), strings.Join(returned, ", "))
		}
		var file bytes.Buffer
		fmt.Fprintln(&file, "// Code generated by generate-storage-rpc; DO NOT EDIT.\n\npackage rpcbackend\n\nimport (")
		paths := make([]string, 0, len(imports))
		for path := range imports {
			paths = append(paths, path)
		}
		sort.Strings(paths)
		for _, path := range paths {
			fmt.Fprintf(&file, "%q\n", path)
		}
		fmt.Fprintln(&file, ")")
		file.Write(body.Bytes())
		content, err := format.Source(file.Bytes())
		if err != nil {
			panic(err)
		}
		if err = os.WriteFile(filepath.Join(dir, fmt.Sprintf("client_%02d.go", part)), content, 0600); err != nil {
			panic(err)
		}
	}
}

func collectImports(t reflect.Type, imports map[string]bool) {
	if t.PkgPath() != "" {
		imports[t.PkgPath()] = true
		return
	}
	switch t.Kind() {
	case reflect.Pointer, reflect.Slice, reflect.Array:
		collectImports(t.Elem(), imports)
	case reflect.Map:
		collectImports(t.Key(), imports)
		collectImports(t.Elem(), imports)
	case reflect.Func:
		for i := 0; i < t.NumIn(); i++ {
			collectImports(t.In(i), imports)
		}
		for i := 0; i < t.NumOut(); i++ {
			collectImports(t.Out(i), imports)
		}
	}
}
