    source_id TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(owner,recording_id),
    FOREIGN KEY(owner,source_id) REFERENCES recording_source_links(owner,source_id) ON DELETE CASCADE
);

CREATE TABLE recording_cover_preferences (
    owner TEXT COLLATE "C" NOT NULL,
    recording_id TEXT COLLATE "C" NOT NULL REFERENCES recordings(id) ON DELETE CASCADE,
    revision BIGINT NOT NULL CHECK(revision>0),
    object_id TEXT COLLATE "C",
    PRIMARY KEY(owner,recording_id)
);

CREATE TABLE metadata_automation (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    scan_job_id TEXT COLLATE "C" NOT NULL REFERENCES jobs(id),
    scan_generation BIGINT NOT NULL,
    plan_digest TEXT COLLATE "C" NOT NULL,
    root_id TEXT COLLATE "C" NOT NULL,
    source_id TEXT COLLATE "C" NOT NULL REFERENCES tracks(id),
    asset_id TEXT COLLATE "C" NOT NULL,
    asset_version TEXT COLLATE "C" NOT NULL,
    reason TEXT COLLATE "C" NOT NULL CHECK(reason IN ('automatic','importLyrics','importArtwork','refreshMetadata')),
    state TEXT COLLATE "C" NOT NULL CHECK(state IN ('queued','preparing','running','completed','skipped','failed')),
    policy TEXT COLLATE "C",
    job_id TEXT COLLATE "C" REFERENCES enrichment_jobs(id),
    failure_code TEXT COLLATE "C",
    created_at TEXT COLLATE "C" NOT NULL,
    UNIQUE(scan_job_id,scan_generation,source_id,reason)
);

CREATE TABLE metadata_automation_actions (
    trigger_id TEXT COLLATE "C" NOT NULL REFERENCES "metadata_automation"(id),
    field TEXT COLLATE "C" NOT NULL,
    language TEXT COLLATE "C" NOT NULL,
    expected_revision BIGINT NOT NULL,
    document TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(trigger_id,field,language)
);

CREATE TABLE refresh_task_cancellations (
