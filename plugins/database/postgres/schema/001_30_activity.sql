CREATE TABLE works (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    content_type TEXT COLLATE "C" NOT NULL,
    title TEXT COLLATE "C" NOT NULL,
    description TEXT COLLATE "C" NOT NULL,
    revision BIGINT NOT NULL CHECK(revision>=1),
    document TEXT COLLATE "C" NOT NULL,
    show_in_track_list BIGINT NOT NULL DEFAULT 0 CHECK(show_in_track_list IN (0,1))
);

CREATE TABLE work_external_ids (
    work_id TEXT COLLATE "C" NOT NULL REFERENCES works(id) ON DELETE CASCADE,
    namespace TEXT COLLATE "C" NOT NULL,
    value TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(work_id,namespace,value)
);

CREATE TABLE work_credits (
    work_id TEXT COLLATE "C" NOT NULL REFERENCES works(id) ON DELETE CASCADE,
    role TEXT COLLATE "C" NOT NULL,
    name TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(work_id,role,name)
);

CREATE TABLE work_tags (
    work_id TEXT COLLATE "C" NOT NULL REFERENCES works(id) ON DELETE CASCADE,
    tag TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(work_id,tag)
);

CREATE TABLE work_packages (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    work_id TEXT COLLATE "C" NOT NULL REFERENCES works(id) ON DELETE CASCADE,
    provider_id TEXT COLLATE "C" NOT NULL,
    root_id TEXT COLLATE "C" NOT NULL,
    relative_path TEXT COLLATE "C" NOT NULL,
    revision BIGINT NOT NULL CHECK(revision>=1),
    document TEXT COLLATE "C" NOT NULL,
    kind TEXT COLLATE "C" NOT NULL DEFAULT 'directory' CHECK(kind IN ('directory','cd_dump')),
    UNIQUE(owner,provider_id,root_id,relative_path)
);

CREATE TABLE recording_default_sources (
    owner TEXT COLLATE "C" NOT NULL,
