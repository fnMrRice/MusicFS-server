    requested_at TEXT COLLATE "C" NOT NULL,
    completed_at TEXT COLLATE "C"
);

CREATE TABLE retired_fingerprint_evidence (
    kind TEXT COLLATE "C" NOT NULL CHECK(kind IN ('job','index')),
