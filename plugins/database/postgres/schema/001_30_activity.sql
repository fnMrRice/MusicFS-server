CREATE TABLE remote_playlists (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    instance_id TEXT COLLATE "C" NOT NULL,
    account_id TEXT COLLATE "C" NOT NULL,
    external_id TEXT COLLATE "C" NOT NULL,
    binding_revision BIGINT NOT NULL,
    revision BIGINT NOT NULL,
    document TEXT COLLATE "C" NOT NULL,
    catalog_job_id TEXT COLLATE "C",
    UNIQUE(owner,instance_id,account_id,external_id)
);

CREATE TABLE remote_sources (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    instance_id TEXT COLLATE "C" NOT NULL,
    account_id TEXT COLLATE "C" NOT NULL,
    external_id TEXT COLLATE "C" NOT NULL,
    document TEXT COLLATE "C" NOT NULL,
    UNIQUE(owner,instance_id,account_id,external_id)
);

CREATE TABLE remote_playlist_snapshots (
    playlist_id TEXT COLLATE "C" NOT NULL REFERENCES remote_playlists(id),
    revision BIGINT NOT NULL,
    owner TEXT COLLATE "C" NOT NULL,
    document TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(playlist_id,revision)
);

CREATE TABLE remote_sync_jobs (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    playlist_id TEXT COLLATE "C" NOT NULL REFERENCES remote_playlists(id),
    state TEXT COLLATE "C" NOT NULL CHECK(state IN ('queued','running','succeeded','failed','cancelled')),
    generation BIGINT NOT NULL,
    binding_revision BIGINT NOT NULL,
    document TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE personal_playlists (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    rule_revision BIGINT NOT NULL,
    hide_revision BIGINT NOT NULL,
    snapshot_revision BIGINT NOT NULL,
    document TEXT COLLATE "C" NOT NULL
);

CREATE TABLE personal_playlist_snapshots (
    playlist_id TEXT COLLATE "C" NOT NULL REFERENCES personal_playlists(id),
    revision BIGINT NOT NULL,
    owner TEXT COLLATE "C" NOT NULL,
    document TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(playlist_id,revision)
);

CREATE TABLE playlist_hidden_rules (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    playlist_id TEXT COLLATE "C" NOT NULL REFERENCES personal_playlists(id),
    active BIGINT NOT NULL CHECK(active IN(0,1)),
    document TEXT COLLATE "C" NOT NULL
);

CREATE TABLE playlist_changes (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    playlist_id TEXT COLLATE "C" NOT NULL REFERENCES personal_playlists(id),
    document TEXT COLLATE "C" NOT NULL
);

CREATE TABLE timeline_evidence (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    recording_id TEXT COLLATE "C" NOT NULL,
    from_source TEXT COLLATE "C" NOT NULL,
    to_source TEXT COLLATE "C" NOT NULL,
    revision BIGINT NOT NULL CHECK(revision>0),
    revoked_at TEXT COLLATE "C",
    document TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE processed_cache (
    id TEXT COLLATE "C" PRIMARY KEY,
    cache_key TEXT COLLATE "C" NOT NULL UNIQUE,
    owner TEXT COLLATE "C" NOT NULL,
    asset_id TEXT COLLATE "C" NOT NULL,
    asset_version TEXT COLLATE "C" NOT NULL,
    size_bytes BIGINT NOT NULL CHECK(size_bytes>0),
    sha256 TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    last_used_at TEXT COLLATE "C" NOT NULL,
    document TEXT COLLATE "C" NOT NULL
);

CREATE TABLE catalog_queries (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    query TEXT COLLATE "C" NOT NULL,
    revision TEXT COLLATE "C" NOT NULL,
    total BIGINT NOT NULL CHECK(total>=0),
    expires_at TEXT COLLATE "C" NOT NULL,
    cancelled BIGINT NOT NULL DEFAULT 0 CHECK(cancelled IN (0,1)),
    idempotency_key TEXT COLLATE "C" NOT NULL
);

CREATE TABLE catalog_query_items (
    query_id TEXT COLLATE "C" NOT NULL REFERENCES catalog_queries(id) ON DELETE CASCADE,
    position BIGINT NOT NULL CHECK(position>=0),
    document TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(query_id,position)
);

CREATE TABLE catalog_query_cursors (
    id TEXT COLLATE "C" PRIMARY KEY,
    query_id TEXT COLLATE "C" NOT NULL REFERENCES catalog_queries(id) ON DELETE CASCADE,
    position BIGINT NOT NULL CHECK(position>=0),
    UNIQUE(query_id,position)
);

