-- 业务文本按 UTF-8 字节比较，数据库的默认区域设置不会改变身份匹配、排序和分页边界。
CREATE TABLE users (
    id TEXT COLLATE "C" PRIMARY KEY,
    role TEXT COLLATE "C" NOT NULL
);

CREATE TABLE auth_sessions (
    id TEXT COLLATE "C" PRIMARY KEY,
    user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id),
    csrf TEXT COLLATE "C" NOT NULL,
    expires_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE jobs (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    target TEXT COLLATE "C" NOT NULL,
    kind TEXT COLLATE "C" NOT NULL,
    generation BIGINT NOT NULL,
    state TEXT COLLATE "C" NOT NULL,
    observed BIGINT NOT NULL DEFAULT 0,
    complete BIGINT NOT NULL DEFAULT 0,
    error TEXT COLLATE "C",
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL,
    last_success_at TEXT COLLATE "C",
    plan TEXT COLLATE "C" NOT NULL,
    plan_digest TEXT COLLATE "C" NOT NULL,
    attempt_count BIGINT NOT NULL DEFAULT 0 CHECK(attempt_count>=0 AND attempt_count<=3),
    max_attempts BIGINT NOT NULL DEFAULT 3 CHECK(max_attempts=3),
    next_attempt_at TEXT COLLATE "C",
    last_attempt_at TEXT COLLATE "C"
);

CREATE TABLE idempotency (
    owner TEXT COLLATE "C" NOT NULL,
    route TEXT COLLATE "C" NOT NULL,
    key TEXT COLLATE "C" NOT NULL,
    digest TEXT COLLATE "C" NOT NULL,
    result TEXT COLLATE "C" NOT NULL,
    expires_at TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(owner,route,key)
);

CREATE TABLE library_revision (
    singleton BIGINT PRIMARY KEY CHECK(singleton=1),
    revision BIGINT NOT NULL
);

CREATE TABLE tracks (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    provider TEXT COLLATE "C" NOT NULL,
    external_id TEXT COLLATE "C" NOT NULL,
    root_id TEXT COLLATE "C" NOT NULL,
    path TEXT COLLATE "C" NOT NULL,
    version TEXT COLLATE "C" NOT NULL,
    asset_id TEXT COLLATE "C" NOT NULL,
    mime TEXT COLLATE "C" NOT NULL,
    size BIGINT NOT NULL,
    document TEXT COLLATE "C" NOT NULL,
    UNIQUE(owner,provider,external_id)
);

CREATE TABLE library_snapshots (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    provider TEXT COLLATE "C" NOT NULL,
    revision TEXT COLLATE "C" NOT NULL,
    expires_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE library_snapshot_items (
    snapshot_id TEXT COLLATE "C" NOT NULL REFERENCES library_snapshots(id) ON DELETE CASCADE,
    position BIGINT NOT NULL,
    document TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(snapshot_id,position)
);

CREATE TABLE library_cursors (
    id TEXT COLLATE "C" PRIMARY KEY,
    snapshot_id TEXT COLLATE "C" NOT NULL REFERENCES library_snapshots(id) ON DELETE CASCADE,
    position BIGINT NOT NULL
);

CREATE TABLE playback_sessions (
    id TEXT COLLATE "C" PRIMARY KEY,
    auth_session TEXT COLLATE "C" NOT NULL,
    user_id TEXT COLLATE "C" NOT NULL,
    description TEXT COLLATE "C" NOT NULL,
    state TEXT COLLATE "C" NOT NULL,
    expires_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE config_operations (
    id TEXT COLLATE "C" PRIMARY KEY,
    config_path TEXT COLLATE "C" NOT NULL,
    idempotency_key TEXT COLLATE "C" NOT NULL,
    digest TEXT COLLATE "C" NOT NULL,
    previous_revision TEXT COLLATE "C" NOT NULL,
    next_revision TEXT COLLATE "C" NOT NULL,
    plugin_id TEXT COLLATE "C" NOT NULL,
    instance_id TEXT COLLATE "C" NOT NULL,
    enabled BIGINT NOT NULL CHECK(enabled IN (0, 1)),
    status TEXT COLLATE "C" NOT NULL CHECK(status IN ('prepared', 'saved', 'applied', 'notSaved', 'superseded')),
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    UNIQUE(config_path, idempotency_key)
);

CREATE TABLE source_assets (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    track_id TEXT COLLATE "C" NOT NULL,
    version TEXT COLLATE "C" NOT NULL,
    current BIGINT NOT NULL CHECK(current IN (0,1)),
    document TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    invalidated_at TEXT COLLATE "C",
    file_sha512 BYTEA CHECK(file_sha512 IS NULL OR length(file_sha512)=64)
);

CREATE TABLE asset_evidence (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    asset_id TEXT COLLATE "C" NOT NULL REFERENCES source_assets(id),
    kind TEXT COLLATE "C" NOT NULL,
    origin TEXT COLLATE "C" NOT NULL,
    generation BIGINT NOT NULL CHECK(generation>0),
    status TEXT COLLATE "C" NOT NULL,
    digest BYTEA CHECK(digest IS NULL OR length(digest)=64),
    document TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    invalidated_at TEXT COLLATE "C",
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    UNIQUE(asset_id,kind,origin,generation)
);

CREATE TABLE hash_jobs (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    asset_id TEXT COLLATE "C" NOT NULL REFERENCES source_assets(id),
    generation BIGINT NOT NULL CHECK(generation>0),
    state TEXT COLLATE "C" NOT NULL,
    automatic BIGINT NOT NULL CHECK(automatic IN (0,1)),
    document TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE hash_conflicts (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    asset_id TEXT COLLATE "C" NOT NULL REFERENCES source_assets(id),
    provider_evidence_id TEXT COLLATE "C" NOT NULL REFERENCES asset_evidence(id),
    verified_evidence_id TEXT COLLATE "C" NOT NULL REFERENCES asset_evidence(id),
    document TEXT COLLATE "C" NOT NULL,
    resolved_at TEXT COLLATE "C",
    UNIQUE(provider_evidence_id,verified_evidence_id)
);

CREATE TABLE provider_scan_leases (
    owner TEXT COLLATE "C" NOT NULL,
    provider TEXT COLLATE "C" NOT NULL,
    last_generation BIGINT NOT NULL CHECK(last_generation>=0),
    active_job_id TEXT COLLATE "C" REFERENCES jobs(id),
    PRIMARY KEY(owner,provider)
);

CREATE TABLE fingerprint_jobs (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    asset_id TEXT COLLATE "C" NOT NULL REFERENCES source_assets(id),
    generation BIGINT NOT NULL CHECK(generation>0),
    state TEXT COLLATE "C" NOT NULL,
    automatic BIGINT NOT NULL CHECK(automatic IN (0,1)),
    request_digest TEXT COLLATE "C" NOT NULL,
    request_start_ms BIGINT NOT NULL,
    request_duration_ms BIGINT NOT NULL,
    config_revision TEXT COLLATE "C" NOT NULL,
    result_id TEXT COLLATE "C",
    document TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE media_publications (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    object_id TEXT COLLATE "C" NOT NULL UNIQUE,
    purpose TEXT COLLATE "C" NOT NULL,
    target_id TEXT COLLATE "C" NOT NULL,
    generation BIGINT NOT NULL CHECK(generation>0),
    status TEXT COLLATE "C" NOT NULL,
    document TEXT COLLATE "C" NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE fingerprint_indexes (
    id TEXT COLLATE "C" PRIMARY KEY,
    owner TEXT COLLATE "C" NOT NULL,
    asset_id TEXT COLLATE "C" NOT NULL REFERENCES source_assets(id),
    job_id TEXT COLLATE "C" NOT NULL REFERENCES fingerprint_jobs(id),
    publication_id TEXT COLLATE "C" NOT NULL UNIQUE REFERENCES media_publications(id),
    object_id TEXT COLLATE "C" NOT NULL UNIQUE,
    request_digest TEXT COLLATE "C" NOT NULL,
    current BIGINT NOT NULL CHECK(current IN (0,1)),
    document TEXT COLLATE "C" NOT NULL,
    computed_at TEXT COLLATE "C" NOT NULL
);
